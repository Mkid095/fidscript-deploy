import type { Metadata } from 'next';
import { DM_Sans, JetBrains_Mono, Plus_Jakarta_Sans } from 'next/font/google';
import { cookies } from 'next/headers';

import './globals.css';

// The mailbox design's typefaces: DM Sans for the body, Plus Jakarta Sans for
// the display headings, JetBrains Mono for ids, addresses and counts.
const dmSans = DM_Sans({
  variable: '--font-dm-sans',
  subsets: ['latin'],
});

const jakarta = Plus_Jakarta_Sans({
  variable: '--font-jakarta',
  subsets: ['latin'],
});

const mono = JetBrains_Mono({
  variable: '--font-jetbrains-mono',
  subsets: ['latin'],
});

export const metadata: Metadata = {
  title: {
    default: 'FIDScript Mail',
    template: '%s · FIDScript Mail',
  },
  description:
    'The self-hosted mail platform: the mailboxes, the messages and the templates, on your own hardware.',
  // The favicon set, generated by RealFaviconGenerator and served from
  // public/. This export is the once-for-all place for the head markup:
  // Next emits these tags on every page.
  icons: {
    icon: [
      { url: '/favicon-96x96.png', sizes: '96x96', type: 'image/png' },
      { url: '/favicon.svg', type: 'image/svg+xml' },
    ],
    apple: [{ url: '/apple-touch-icon.png', sizes: '180x180' }],
    shortcut: '/favicon.ico',
  },
  manifest: '/site.webmanifest',
  appleWebApp: {
    title: 'Fidscript',
    statusBarStyle: 'default',
  },
};

/**
 * The root layout.
 *
 * The theme is read from the platform's own `fidscript_theme` cookie, the
 * same one the console writes — the webmail answers from the same
 * fidscript.com domain, so the operator's choice in one carries into the
 * other. No cookie: the answer is the console's default, dark. The server
 * renders the right class, so there is no flash of the wrong theme.
 */
export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const theme =
    (await cookies()).get('fidscript_theme')?.value === 'light'
      ? 'light'
      : 'dark';

  return (
    <html lang="en" className={theme === 'light' ? 'light' : 'dark'}>
      <body
        className={`${dmSans.variable} ${jakarta.variable} ${mono.variable} antialiased`}
      >
        {children}
      </body>
    </html>
  );
}
